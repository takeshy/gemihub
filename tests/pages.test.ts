const page = (id: string): ShopPage => ({ id, slug: id, title: id, navigationLabel: id, body: "## ご案内\n\n内容", layout: "standard", imageUrl: "" });
process.env.DEMO_MODE = "true";

test("header/footer releases preserve other drafts and scope pen changes", () => {
  const before = { ...structuredClone(sample), pages: [page("faq")] };
  const local = structuredClone(before);
  local.header.title = "新しいヘッダー";
  local.footer.text = "ローカルのフッター";
  local.pages[0].body = "未反映の本文";
  const scope = { kind: "part" as const, part: "header" as const };
  const released = scopedConfig(before, local, scope);
  assert.equal(released.header.title, local.header.title);
  assert.deepEqual(released.footer, before.footer);
  assert.deepEqual(released.pages, before.pages);
  const latest = structuredClone(released); latest.footer.text = "別端末からの更新";
  const rebased = rebaseDraft(before, local, latest, scope);
  assert.deepEqual(rebased.config.header, released.header);
  assert.deepEqual(rebased.source.header, released.header);
  assert.equal(rebased.config.footer.text, local.footer.text);
  assert.deepEqual(rebased.source.footer, before.footer);
  assert.equal(rebased.config.pages[0].body, local.pages[0].body);
  const shared = scopedConfig(before, local, { kind: "shared" });
  assert.deepEqual(shared.header, before.header);
  assert.deepEqual(shared.footer, before.footer);
  const pen = { ...before, header: local.header };
  assert.equal(validateVisualChange(before, pen, "part:header").header.title, local.header.title);
  assert.throws(() => validateVisualChange(before, local, "part:header"));
  const files = artifacts(released, '<title></title><div id="root"></div>');
  assert.ok(files["web/parts/header.html"].includes(local.header.title));
  assert.equal(JSON.parse(files["web/parts/footer.json"]).text, before.footer.text);
});

test("page validation, safe HTML exports, scoped changes and local rebase", () => {
  const before = { ...structuredClone(sample), pages: [page("faq"), page("access")] };
  const local = structuredClone(before);
  local.pages[0].body = "変更したFAQ";
  local.pages[1].body = "まだ反映しない店舗紹介";
  local.menus[0].price++;
  const released = scopedConfig(before, local, { kind: "page", pageId: "faq" });
  assert.equal(released.pages.find(p => p.id === "faq")!.body, "変更したFAQ");
  assert.equal(released.pages.find(p => p.id === "access")!.body, before.pages[1].body);
  assert.equal(released.menus[0].price, before.menus[0].price);
  const shared = scopedConfig(before, { ...local, name: "共通の店名を変更" }, { kind: "shared" });
  assert.equal(shared.name, "共通の店名を変更");
  assert.deepEqual(shared.pages, before.pages);
  assert.deepEqual(shared.menus, before.menus);
  const remaining = rebaseDraft(before, local, released, { kind: "page", pageId: "faq" }).config;
  assert.equal(remaining.pages.find(p => p.id === "access")!.body, "まだ反映しない店舗紹介");
  assert.equal(remaining.menus[0].price, released.menus[0].price);
  const concurrentlyChanged = structuredClone(released);
  concurrentlyChanged.pages.find(p => p.id === "access")!.body = "別の端末から変更";
  concurrentlyChanged.name = "別の端末の新しい店名";
  const rebased = rebaseDraft(before, local, concurrentlyChanged, { kind: "page", pageId: "faq" });
  assert.equal(rebased.config.name, concurrentlyChanged.name);
  assert.equal(rebased.config.pages.find(p => p.id === "access")!.body, local.pages[1].body);
  assert.equal(rebased.source.pages.find(p => p.id === "access")!.body, before.pages[1].body);
  assert.equal(same(scopedSource(rebased.source, { kind: "page", pageId: "access" }), scopedSource(concurrentlyChanged, { kind: "page", pageId: "access" })), false);

  assert.equal(shopSchema.safeParse({ ...before, pages: [page("faq"), page("faq")] }).success, false);
  assert.equal(shopSchema.safeParse({ ...before, pages: [{ ...page("faq"), slug: "../admin" }] }).success, false);
  const unsafe = { ...page("faq"), title: '<script>alert(1)</script>', body: '<script>alert(1)</script>\n\n[危険](javascript:alert(1))' };
  const html = renderCustomPage(unsafe, '<title></title><div id="root"></div>');
  assert.ok(!html.includes('<script>'));
  assert.ok(!html.includes('href="javascript:'));
  assert.ok(artifacts(before, '<title></title><div id="root"></div>')["web/pages/faq.html"].includes("ご案内"));
  const pen = structuredClone(before); pen.pages[0].body = "ペンで変更";
  assert.equal(validateVisualChange(before, pen, "page:faq:body").pages[0].body, "ペンで変更");
  pen.pages[1].body = "他のページも変更";
  assert.throws(() => validateVisualChange(before, pen, "page:faq:body"));
});

test("per-page releases stay scoped and detect conflicts; direct saves overwrite their section", async t => {
  const store = new Store(":memory:");
  const shop = await store.createShop("owner@example.com");
  shop.published = { ...structuredClone(sample), pages: [page("faq"), page("access")] };
  await store.saveShop(shop);
  const server = createApp(store);
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  process.env.APP_ORIGIN = origin;
  t.after(() => { server.close(); void store.close(); });
  for (const [id, email] of [["owner", shop.owner], ["outsider", "other@example.com"]]) await store.put("session", digest(id), { user: { email, name: id, role: "owner" }, expires: Date.now() + 600000 });
  async function request(action: string, data?: unknown, user = "owner") {
    const res = await fetch(`${origin}/api/shops/${shop.id}/${action}`, { method: data === undefined ? "GET" : "POST", headers: { Origin: origin, Cookie: `gemihub_session=${user}`, "Content-Type": "application/json" }, body: data === undefined ? undefined : JSON.stringify(data) });
    return { status: res.status, body: await res.json() };
  }
  const original = structuredClone(shop.published);
  const draft = structuredClone(original);
  draft.pages[0].body = "公開するFAQ";
  draft.pages[1].body = "ローカルだけの店舗紹介";
  draft.menus[0].price = 9999;
  const created = await request("plan", { text: "FAQだけ反映", config: draft, local: { base: 0, source: original, requestId: randomUUID(), scope: { kind: "page", pageId: "faq" } } });
  assert.equal(created.status, 200);
  await request(`plans/${created.body.id}/approve`, {});
  assert.equal((await request(`plans/${created.body.id}/publish`, {})).status, 200);
  let current = (await store.shop(shop.id))!.published!;
  assert.equal(current.pages.find(p => p.id === "access")!.body, original.pages[1].body);
  assert.equal(current.menus[0].price, original.menus[0].price);
  const live = await request("live-settings/menus");
  const menus = structuredClone(live.body.config.menus); menus[0].price = 6000;
  const saving = { value: menus, previous: live.body.config.menus, requestId: randomUUID() };
  assert.equal((await request("live-settings/menus", saving, "outsider")).status, 403);
  assert.equal((await request("live-settings/menus", saving)).status, 200);
  const revision = (await store.shop(shop.id))!.revision;
  assert.equal((await request("live-settings/menus", saving)).status, 200);
  assert.equal((await store.shop(shop.id))!.revision, revision);
  assert.equal((await request("live-settings/menus", { ...saving, requestId: randomUUID() })).status, 200);
  // An unrelated live price change and released FAQ do not prevent releasing access.
  const second = await request("plan", { text: "店舗紹介だけ反映", config: draft, local: { base: 0, source: original, requestId: randomUUID(), scope: { kind: "page", pageId: "access" } } });
  assert.equal(second.status, 200);
  await request(`plans/${second.body.id}/approve`, {});
  await request(`plans/${second.body.id}/publish`, {});
  current = (await store.shop(shop.id))!.published!;
  assert.equal(current.menus[0].price, 6000);
  assert.equal(current.pages.find(p => p.id === "faq")!.body, "公開するFAQ");
  assert.equal(current.pages.find(p => p.id === "access")!.body, "ローカルだけの店舗紹介");
  const stale = await request("plan", { text: "古いFAQ", config: draft, local: { base: 0, source: original, requestId: randomUUID(), scope: { kind: "page", pageId: "faq" } } });
  assert.equal(stale.status, 409);
  const removed = { ...current, pages: current.pages.filter(p => p.id !== "faq") };
  const deletion = await request("plan", { text: "FAQ削除", config: removed, local: { base: 0, source: current, requestId: randomUUID(), scope: { kind: "page", pageId: "faq" } } });
  assert.equal(deletion.status, 200);
  await request(`plans/${deletion.body.id}/approve`, {}); await request(`plans/${deletion.body.id}/publish`, {});
  assert.equal((await store.shop(shop.id))!.published!.pages.length, 1);
  const content = { title: "保存で公開する記事", slug: "live-save", category: "blogs", date: "2026-10-31", excerpt: "", body: "本文" };
  const post = await request("posts", { content, publish: true });
  assert.equal(post.status, 200);
  assert.equal(post.body.published.title, content.title);
  const updated = await request(`posts/${post.body.id}/save`, { version: post.body.version, content: { ...content, body: "更新した本文" }, publish: true });
  assert.equal(updated.status, 200);
  assert.equal(updated.body.published.body, "更新した本文");
});

import assert from "node:assert/strict";
import { chromium } from "playwright";
const origin = process.env.STORYBOOK_URL || "http://localhost:6005";
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {}), args: ["--no-sandbox"] });
try {
  const entries = Object.values((await (await fetch(`${origin}/index.json`)).json()).entries);
  for (const locale of ["en-US", "ja-JP"]) {
    const context = await browser.newContext({ locale, viewport: { width: 390, height: 844 } });
    const page = await context.newPage();
    async function open(suffix) {
      const entry = entries.find(entry => entry.id.endsWith(`--${suffix}`)); assert.ok(entry, suffix);
      await page.goto(`${origin}/iframe.html?id=${encodeURIComponent(entry.id)}&viewMode=story`);
    }
    await open("customer");
    const date = page.getByRole("textbox", { name: "ご希望の日付（日本時間）", exact: true });
    await date.waitFor();
    assert.match(await date.inputValue(), /^\d{4}\/\d{2}\/\d{2}$/);
    await date.fill("2099/02/28"); await date.blur();
    assert.equal(await date.inputValue(), "2099/02/28");
    assert.equal(await date.evaluate(input => input.checkValidity()), true);
    await date.fill("2099/02/29");
    assert.equal(await date.evaluate(input => input.checkValidity()), false);
    await date.fill("2099-03-01"); await date.blur();
    assert.equal(await date.inputValue(), "2099/03/01");
    await page.locator('.date-native-picker').evaluate(input => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set.call(input, "2099-04-05"); input.dispatchEvent(new Event("change", { bubbles: true })); });
    assert.equal(await date.inputValue(), "2099/04/05");
    await date.fill(""); await date.pressSequentially("2099/11/15"); await date.blur();
    assert.equal(await date.inputValue(), "2099/11/15");
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await open("list");
    await page.getByLabel("集計期間").selectOption("custom");
    const since = page.getByRole("textbox", { name: "開始日（日本時間）", exact: true });
    await since.fill("2026/01/02"); await since.blur();
    assert.equal(await since.inputValue(), "2026/01/02");
    await page.getByText("集計対象：2026-01-02 以降", { exact: false }).waitFor();
    await open("local-editor");
    await page.getByText("サンプルデータを編集", { exact: true }).click();
    const start = page.getByRole("textbox", { name: "開始日時（日本時間）", exact: true }).first();
    await start.waitFor();
    assert.match(await start.inputValue(), /^\d{4}\/\d{2}\/\d{2} \d{2}:\d{2}$/);
    await start.fill("2026/11/01 09:30"); await start.blur();
    assert.equal(await start.inputValue(), "2026/11/01 09:30");
    assert.equal(await start.evaluate(input => input.checkValidity()), true);
    await open("contact");
    const contact = page.locator(".contact-form");
    assert.equal(await contact.getByRole("textbox", {name:"お名前",exact:true}).inputValue(), "山田 花子");
    const email = contact.getByRole("textbox", {name:"メールアドレス",exact:true});
    assert.equal(await email.inputValue(), "guest@example.com");
    assert.equal(await email.getAttribute("readonly"), "");
    await contact.getByRole("textbox", {name:"ご相談内容",exact:true}).fill("初めての予約について教えてください。");
    await contact.getByRole("button", {name:"お問い合わせを送る →",exact:true}).click();
    await page.getByText("お問い合わせを受け付けました。返信はメールでお送りします。", {exact:true}).waitFor();
    await open("registration");
    const registration = page.locator(".customer-registration");
    await registration.getByRole("heading", {name:"会員情報を登録する",exact:true}).waitFor();
    await registration.getByRole("textbox", {name:"お名前",exact:true}).fill("登録したお名前");
    await registration.getByRole("textbox", {name:"生年月日",exact:true}).fill("1995/02/28");
    await registration.getByLabel("性別", {exact:true}).selectOption("not_specified");
    await registration.getByRole("button", {name:"登録して予約へ進む",exact:true}).click();
    await page.getByRole("textbox", {name:"ご希望の日付（日本時間）",exact:true}).waitFor();
    assert.equal(await page.getByRole("textbox", {name:"お名前",exact:true}).inputValue(), "登録したお名前");
    await page.locator(".public-nav").getByRole("button", {name:"お問い合わせ",exact:true}).click();
    assert.equal(await page.locator(".contact-form").getByRole("textbox", {name:"お名前",exact:true}).inputValue(), "登録したお名前");
    await page.locator(".public-nav").getByRole("button", {name:"マイページ",exact:true}).click();
    await page.getByRole("button", {name:"会員情報を変更",exact:true}).click();
    assert.equal(await page.getByRole("textbox", {name:"生年月日",exact:true}).inputValue(), "1995/02/28");
    await open("anonymous");
    await page.locator(".about").waitFor();
    assert.equal(await page.locator(".public-nav .active").innerText(), "お店のこと");
    await page.getByRole("region",{name:"会員登録・ログイン",exact:true}).getByRole("link", { name: "会員登録", exact: true }).waitFor();
    await page.getByRole("region",{name:"会員登録・ログイン",exact:true}).getByRole("link", { name: "ログイン", exact: true }).waitFor();
    assert.equal(await page.locator(".login-strip").count(), 0);
    assert.equal(await page.locator(".site-header .public-auth").count(),0);
    assert.ok(await page.evaluate(()=>document.querySelector('.site-header').getBoundingClientRect().bottom<=document.querySelector('.public-auth').getBoundingClientRect().top));
    await page.getByRole("region",{name:"会員登録・ログイン",exact:true}).getByText("初めての方",{exact:true}).waitFor();
    await page.getByRole("region",{name:"会員登録・ログイン",exact:true}).getByText("登録済みの方",{exact:true}).waitFor();
    await page.getByRole("button", { name: "ご予約", exact: true }).click();
    assert.equal(await page.getByText("ご予約は Google アカウントでログインしてご利用ください。", { exact: true }).count(),0);
    assert.equal(await page.locator(".login-strip").count(),0);
    assert.equal(await page.getByRole("region",{name:"会員登録・ログイン",exact:true}).count(),1);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({path:`/tmp/omaiweb-auth-entry-${locale}-390.png`,fullPage:true});
    await page.setViewportSize({width:1280,height:900});
    assert.ok(await page.evaluate(()=>document.querySelector('.site-header').getBoundingClientRect().bottom<=document.querySelector('.public-auth').getBoundingClientRect().top));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:`/tmp/omaiweb-auth-entry-${locale}-1280.png`,fullPage:true});
    await context.close();
    console.log(`${locale}: slash date entry, calendar selection, invalid date validation, ISO filter values and sample times passed.`);
  }
} finally { await browser.close(); }
